"""Generate the built-in animation library (original procedural art).

    uv run --with pillow python scripts/make_library.py

Writes 32x32 GIFs and ``index.json`` into custom_components/idm_studio/library/.
Everything here is generated by this script, so it carries the repository's
license and needs no third-party attribution.
"""

from __future__ import annotations

import colorsys
import json
import math
import random
from pathlib import Path

from PIL import Image, ImageDraw

N = 32
OUT = Path(__file__).parents[1] / "custom_components/idm_studio/library"


def hsv(h: float, s: float = 1.0, v: float = 1.0) -> tuple[int, int, int]:
    r, g, b = colorsys.hsv_to_rgb(h % 1.0, max(0, min(1, s)), max(0, min(1, v)))
    return round(r * 255), round(g * 255), round(b * 255)


def blank() -> Image.Image:
    return Image.new("RGB", (N, N), (0, 0, 0))


def fire(frames=24):
    rng = random.Random(1)
    heat = [[0.0] * N for _ in range(N + 2)]
    out = []
    for i in range(frames + 40):
        for x in range(N):
            heat[N + 1][x] = heat[N][x] = rng.random() ** 0.5
        for y in range(N):
            for x in range(N):
                s = heat[y + 1][(x - 1) % N] + heat[y + 1][x] + heat[y + 1][(x + 1) % N] + heat[y + 2][x]
                heat[y][x] = max(0.0, s / 4.0 - 0.022 - 0.02 * rng.random())
        if i >= 40:  # let the flames settle first
            img = blank()
            for y in range(N):
                for x in range(N):
                    t = heat[y][x]
                    t = max(0.0, t - 0.08) * 1.4
                    img.putpixel((x, y), (min(255, int(t * 420)), min(255, int(t * t * 300)), min(255, int(t**4 * 160))))
            out.append(img)
    return out, 60


def rain(frames=32):
    rng = random.Random(2)
    drops = [[rng.randrange(N), rng.randrange(N), rng.choice((1, 1, 2))] for _ in range(26)]
    out = []
    for _ in range(frames):
        img = blank()
        d = ImageDraw.Draw(img)
        for drop in drops:
            x, y, speed = drop
            for k in range(4):
                v = 255 - k * 60
                d.point((x, (y - k) % N), fill=(v // 5, v // 2, v))
            drop[1] = (y + speed) % N
        out.append(img)
    return out, 70


def snow(frames=48):
    rng = random.Random(3)
    flakes = [[rng.uniform(0, N), rng.uniform(0, N), rng.uniform(0.2, 0.6), rng.random() * 6] for _ in range(30)]
    out = []
    for f in range(frames):
        img = blank()
        for flake in flakes:
            x = (flake[0] + math.sin(f / 6 + flake[3]) * 0.8) % N
            v = int(140 + 115 * flake[2] / 0.6)
            img.putpixel((int(x), int(flake[1]) % N), (v, v, 255))
            flake[1] = (flake[1] + flake[2]) % N
        out.append(img)
    return out, 80


def code_rain(frames=40):
    rng = random.Random(4)
    cols = [[rng.randrange(0, N + 12), rng.choice((1, 1, 2)), rng.randrange(6, 16)] for _ in range(N)]
    out = []
    for _ in range(frames):
        img = blank()
        for x, col in enumerate(cols):
            head, speed, length = col
            for k in range(length):
                y = head - k
                if 0 <= y < N:
                    g = 255 if k == 0 else int(220 * (1 - k / length))
                    img.putpixel((x, y), (180, 255, 180) if k == 0 else (0, g, 0))
            col[0] += speed
            if head - length > N:
                col[0] = rng.randrange(-N // 2, 0)
        out.append(img)
    return out, 70


def plasma(frames=36):
    out = []
    for f in range(frames):
        t = f / frames * 2 * math.pi
        img = blank()
        for y in range(N):
            for x in range(N):
                v = (
                    math.sin(x / 5 + t)
                    + math.sin(y / 4 - t)
                    + math.sin((x + y) / 7 + t)
                    + math.sin(math.hypot(x - 16, y - 16) / 4 - t)
                )
                img.putpixel((x, y), hsv(v / 8 + f / frames))
        out.append(img)
    return out, 70


def starfield(frames=40):
    rng = random.Random(5)
    stars = [[rng.uniform(-1, 1), rng.uniform(-1, 1), rng.uniform(0.1, 1)] for _ in range(60)]
    out = []
    for _ in range(frames):
        img = blank()
        for star in stars:
            star[2] -= 0.025
            if star[2] <= 0.05:
                star[:] = [rng.uniform(-1, 1), rng.uniform(-1, 1), 1.0]
            x = int(16 + star[0] / star[2] * 8)
            y = int(16 + star[1] / star[2] * 8)
            if 0 <= x < N and 0 <= y < N:
                v = min(255, int(90 + 300 * (1 - star[2])))
                img.putpixel((x, y), (v, v, v))
        out.append(img)
    return out, 50


HEART = [
    "..XX...XX..",
    ".XXXX.XXXX.",
    "XXXXXXXXXXX",
    "XXXXXXXXXXX",
    "XXXXXXXXXXX",
    ".XXXXXXXXX.",
    "..XXXXXXX..",
    "...XXXXX...",
    "....XXX....",
    ".....X.....",
]


def heartbeat(frames=16):
    out = []
    for f in range(frames):
        beat = [1.0, 1.25, 1.1, 1.3, 1.0] + [1.0] * 11
        scale = beat[f] * 2.2
        img = blank()
        d = ImageDraw.Draw(img)
        w, h = len(HEART[0]) * scale, len(HEART) * scale
        ox, oy = (N - w) / 2, (N - h) / 2 + 1
        for r, row in enumerate(HEART):
            for c, ch in enumerate(row):
                if ch == "X":
                    d.rectangle(
                        (ox + c * scale, oy + r * scale, ox + (c + 1) * scale - 1, oy + (r + 1) * scale - 1),
                        fill=(255, 30 + int(40 * (scale - 2.2)), 70),
                    )
        out.append(img)
    return out, 80


def spinner(frames=24):
    out = []
    for f in range(frames):
        img = blank()
        d = ImageDraw.Draw(img)
        for k in range(12):
            a = (k / 12 + f / frames) * 2 * math.pi
            fade = ((k - 0) % 12) / 11
            c = hsv(0.55, 0.6, 0.15 + 0.85 * fade)
            x, y = 16 + math.cos(a) * 11, 16 + math.sin(a) * 11
            d.ellipse((x - 2, y - 2, x + 2, y + 2), fill=c)
        out.append(img)
    return out, 50


def waves(frames=32):
    out = []
    for f in range(frames):
        img = blank()
        t = f / frames * 2 * math.pi
        for x in range(N):
            for layer, (base, amp, col) in enumerate(
                ((12, 3, (20, 90, 200)), (17, 2.5, (30, 140, 230)), (22, 2, (90, 200, 255)))
            ):
                top = base + amp * math.sin(x / 5 + t * (1 + layer * 0.3) + layer)
                for y in range(int(top), N):
                    img.putpixel((x, y), col)
        img.paste((255, 210, 60), (24, 3, 29, 8))  # sun
        out.append(img)
    return out, 80


def bounce(frames=40):
    out = []
    x, y, vx, vy = 6.0, 6.0, 0.9, 0.0
    trail: list[tuple[float, float]] = []
    for f in range(frames):
        vy += 0.18
        x, y = x + vx, y + vy
        if y > N - 4:
            y, vy = N - 4, -abs(vy) * 0.98
        if x < 3 or x > N - 4:
            vx = -vx
        trail = (trail + [(x, y)])[-6:]
        img = blank()
        d = ImageDraw.Draw(img)
        for k, (tx, ty) in enumerate(trail[:-1]):
            d.ellipse((tx - 1, ty - 1, tx + 1, ty + 1), fill=hsv(f / frames, 1, 0.15 + k * 0.08))
        d.ellipse((x - 3, y - 3, x + 3, y + 3), fill=hsv(f / frames))
        out.append(img)
    return out, 50


def life(frames=48):
    rng = random.Random(6)
    grid = [[rng.random() < 0.32 for _ in range(N)] for _ in range(N)]
    age = [[0] * N for _ in range(N)]
    out = []
    for _ in range(frames):
        img = blank()
        for y in range(N):
            for x in range(N):
                if grid[y][x]:
                    img.putpixel((x, y), hsv(0.33 - min(age[y][x], 20) / 40, 0.9, 1))
        out.append(img)
        new = [[False] * N for _ in range(N)]
        for y in range(N):
            for x in range(N):
                n = sum(grid[(y + dy) % N][(x + dx) % N] for dy in (-1, 0, 1) for dx in (-1, 0, 1)) - grid[y][x]
                new[y][x] = n == 3 or (grid[y][x] and n == 2)
                age[y][x] = age[y][x] + 1 if new[y][x] and grid[y][x] else 0
        grid = new
    return out, 110


def fireworks(frames=48):
    rng = random.Random(7)
    bursts = []
    out = []
    for f in range(frames):
        if f % 10 == 0 or f == 4:
            cx, cy, hue = rng.uniform(8, 24), rng.uniform(6, 16), rng.random()
            bursts.append([[cx, cy, math.cos(a) * s, math.sin(a) * s, hue, 1.0]
                           for a in [k / 32 * 2 * math.pi for k in range(32)]
                           for s in (rng.uniform(0.7, 1.2),)])
        img = blank()
        for burst in bursts:
            for p in burst:
                p[0] += p[2]
                p[1] += p[3]
                p[3] += 0.05
                p[2] *= 0.94
                p[5] *= 0.95
                if 0 <= p[0] < N and 0 <= p[1] < N and p[5] > 0.05:
                    img.putpixel((int(p[0]), int(p[1])), hsv(p[4], 0.7, min(1.0, p[5] * 1.3)))
        bursts = [b for b in bursts if b[0][5] > 0.08]
        out.append(img)
    return out, 60


def rainbow(frames=30):
    out = []
    for f in range(frames):
        img = blank()
        for y in range(N):
            for x in range(N):
                a = math.atan2(y - 15.5, x - 15.5) / (2 * math.pi)
                r = math.hypot(x - 15.5, y - 15.5)
                img.putpixel((x, y), hsv(a + f / frames + r / 60, 1, 1 if r < 16 else 0.5))
        out.append(img)
    return out, 60


LIBRARY = {
    "fire": ("Fire", fire),
    "rain": ("Rain", rain),
    "snow": ("Snow", snow),
    "code-rain": ("Code rain", code_rain),
    "plasma": ("Plasma", plasma),
    "starfield": ("Starfield", starfield),
    "heartbeat": ("Heartbeat", heartbeat),
    "spinner": ("Spinner", spinner),
    "waves": ("Waves", waves),
    "bounce": ("Bouncing ball", bounce),
    "life": ("Game of Life", life),
    "fireworks": ("Fireworks", fireworks),
    "rainbow": ("Rainbow swirl", rainbow),
}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    index = []
    for key, (name, make) in LIBRARY.items():
        frames, delay = make()
        path = OUT / f"{key}.gif"
        frames[0].save(path, save_all=True, append_images=frames[1:], duration=delay, loop=0, optimize=True)
        index.append({"id": key, "name": name, "file": path.name})
        print(f"{path.name}: {len(frames)} frames, {path.stat().st_size} bytes")
    (OUT / "index.json").write_text(json.dumps(index, indent=2) + "\n")


if __name__ == "__main__":
    main()
